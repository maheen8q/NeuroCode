#!/usr/bin/env python3
"""Generates CursorKindNames.hpp: libclang cursor kind value -> the name Python's
clang.cindex gives it (cursor.kind.name). extract_ast.py writes that name into the
"type" field, and features.py matches on it ("FOR_STMT", "CALL_EXPR", ...), so the C++
builder must emit exactly the same strings.

Run when the libclang bindings used by tools/extract_ast.py change:
    python3 src/engine/parse/gen_cursor_kinds.py > src/engine/parse/CursorKindNames.hpp
"""
import clang.cindex as ci

kinds = sorted(ci.CursorKind.get_all_kinds(), key=lambda k: k.value)
names = {k.value: k.name for k in kinds}
assert len(names) == len(kinds), "two kinds share a value"

print("// GENERATED by gen_cursor_kinds.py from the Python clang.cindex bindings. Do not edit.")
print("#pragma once")
print()
print("namespace nc::parse {")
print()
print("// Name that Python's cursor.kind.name gives for a CXCursorKind value, or nullptr if unknown.")
print("inline const char* cursorKindName(int kind) {")
print("    switch (kind) {")
for v in sorted(names):
    print(f'        case {v}: return "{names[v]}";')
print("        default: return nullptr;")
print("    }")
print("}")
print()
print("} // namespace nc::parse")
